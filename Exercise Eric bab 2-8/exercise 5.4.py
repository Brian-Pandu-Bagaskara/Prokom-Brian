# Versi 1: Menjalankan blok 'if' (Warna alien hijau)
print("--- Alien Hijau ---")
warna_alien = 'hijau'

if warna_alien == 'hijau':
    print("Pemain baru saja mendapatkan 5 poin karena menembak alien.")
else:
    print("Pemain baru saja mendapatkan 10 poin.")


# Versi 2: Menjalankan blok 'else' (Warna alien bukan hijau)
print("\n--- Alien Merah ---")
warna_alien = 'merah'

if warna_alien == 'hijau':
    print("Pemain baru saja mendapatkan 5 poin karena menembak alien.")
else:
    print("Pemain baru saja mendapatkan 10 poin.")