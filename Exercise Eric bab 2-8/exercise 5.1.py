# 1. Variabel Makanan
makanan = 'nasi goreng'
print("Apakah makanan == 'nasi goreng'? Saya prediksi True.")
print(makanan == 'nasi goreng')

print("\nApakah makanan == 'mie ayam'? Saya prediksi False.")
print(makanan == 'mie ayam')

