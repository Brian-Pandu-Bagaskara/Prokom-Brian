nama = "\t\n  Brian Pandu  \n"

print("Original:")
print(nama)

# lstrip() menghapus spasi/tab/enter di sebelah KIRI (Left)
print(nama.lstrip()) 

# rstrip() menghapus spasi/tab/enter di sebelah KANAN (Right)
print(nama.rstrip()) 

# strip() menghapus spasi/tab/enter di KEDUA SISI
print(nama.strip())
