# Menggunakan list 9 buah-buahan sebagai contoh agar mudah diambil tengahnya
buah = ['apel', 'pisang', 'ceri', 'durian', 'anggur', 'mangga', 'nanas', 'pepaya', 'semangka']

print("The first three items in the list are:")
print(buah[:3])  # Mengambil 3 item pertama (indeks 0, 1, 2)

print("\nThree items from the middle of the list are:")
print(buah[3:6])  # Mengambil 3 item di tengah (indeks 3, 4, 5)

print("\nThe last three items in the list are:")
print(buah[-3:])  # Mengambil 3 item terakhir menggunakan indeks negatif