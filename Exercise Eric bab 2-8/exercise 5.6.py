usia = 25 # Ubah nilai variabel usia ini untuk menguji kondisi lainnya

if usia < 2:
    print("Orang tersebut adalah seorang bayi.")
elif usia < 4:
    print("Orang tersebut adalah seorang balita.")
elif usia < 13:
    print("Orang tersebut adalah seorang anak-anak.")
elif usia < 20:
    print("Orang tersebut adalah seorang remaja.")
elif usia < 65:
    print("Orang tersebut adalah seorang dewasa.")
else:
    print("Orang tersebut adalah seorang lansia.")